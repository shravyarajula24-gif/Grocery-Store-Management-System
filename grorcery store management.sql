-- 1. Customer Insights ------------------------------------

-- ● How many unique customers have placed orders? 

SELECT 
    COUNT(DISTINCT cust_id)
FROM
    orders;
    
-- ● Which customers have placed the highest number of orders?
SELECT 
    cust_id, COUNT(*) AS total_oders
FROM
    orders
GROUP BY cust_id
ORDER BY total_oders DESC
LIMIT 1;
-- ● What is the total and average purchase value per customer?
SELECT 
    c.cust_id,
    c.cust_name,
    SUM(od.total_price) AS total_purchase,
    AVG(od.total_price) AS avg_purchase
FROM
    customers AS c
        JOIN
    orders AS o ON c.cust_id = o.cust_id
        JOIN
    order_details AS od ON o.ord_id = od.ord_id
GROUP BY c.cust_id ;

-- ● Who are the top 5 customers by total purchase amount?

SELECT 
    c.cust_id, c.cust_name, t.total_purchase
FROM
    (SELECT 
        o.cust_id,
            SUM(od.total_price) AS total_purchase
    FROM
        orders AS o
    JOIN order_details AS od ON o.ord_id = od.ord_id
    GROUP BY o.cust_id
    ORDER BY total_purchase DESC
    LIMIT 5) AS t
        JOIN
    customers AS c ON c.cust_id = t.cust_id;
    
-- 2. Product Performance ----------------------------------------
-- ● How many products exist in each category?
SELECT 
    c.cat_id, c.cat_name, COUNT(p.prod_id) AS num_products
FROM
    categories AS c
        LEFT JOIN
    products AS p ON c.cat_id = p.cat_id
GROUP BY c.cat_id;

-- What is the average price of products by category?
 
SELECT 
    p.cat_id, AVG(p.price) AS avg_price
FROM
    products AS p
GROUP BY p.cat_id;

-- ● Which products have the highest total sales volume (by quantity)?

SELECT p.prod_id, p.prod_name,
       SUM(od.quantity) AS total_quantity,
       RANK() OVER (ORDER BY SUM(od.quantity) DESC) AS sales_rank
FROM products p
JOIN order_details od ON p.prod_id = od.prod_id
GROUP BY p.prod_id, p.prod_name;

-- ● What is the total revenue generated by each product?

SELECT 
    p.prod_name, d.total_revenue
FROM
    products AS p
        JOIN
    (SELECT 
        prod_id, SUM(total_price) AS total_revenue
    FROM
        order_details
    GROUP BY prod_id) AS d ON p.prod_id = d.prod_id;

-- 3. Sales and Order Trends -----------------------------------
-- How many orders have been placed in total?
 SELECT 
    COUNT(*) AS total_orders
FROM
    orders;

-- ● What is the average value per order? 

SELECT 
    ord_id, AVG(total_price) AS order_value
FROM
    order_details
GROUP BY ord_id;

-- ● On which dates were the most orders placed?
 
SELECT 
    order_date, COUNT(*) AS total_orders
FROM
    orders
GROUP BY order_date
ORDER BY total_orders DESC;

--  What are the monthly trends in order volume and revenue? 

CREATE VIEW monthly_trends AS
SELECT 
    MONTH(o.order_date) AS months,
    COUNT(DISTINCT o.ord_id) AS order_volume,
    SUM(od.total_price) AS revenue
FROM orders AS o
JOIN order_details AS od ON o.ord_id = od.ord_id
GROUP BY MONTH(o.order_date);

SELECT * FROM monthly_trends;

-- ● How do order patterns vary across weekdays and weekends? 

SELECT 
    CASE 
        WHEN DAYOFWEEK(order_date) IN (1, 7)
        THEN 'Weekend'
        ELSE 'Weekday'
    END AS day_type,
    COUNT(*) AS total_orders
FROM orders
GROUP BY day_type;

