#Which suppliers contribute the most to total product sales (by revenue)?

WITH supplier_sales AS (
    SELECT p.sup_id, SUM(od.total_price) AS total_prod_sale
    FROM products p
    JOIN order_details od ON p.prod_id = od.prod_id
    GROUP BY p.sup_id)
SELECT s.sup_id, s.sup_name, ss.total_prod_sale
FROM supplier s
JOIN supplier_sales ss ON s.sup_id = ss.sup_id
ORDER BY ss.total_prod_sale DESC;

-- 5 . Employee Performance -------------------------------

#How many employees have processed orders?

SELECT 
    COUNT(DISTINCT emp_id) AS no_emp
FROM
    orders;

#Which employees have handled the most orders?

SELECT e.emp_id, e.emp_name, t.most_ord
FROM employees e
JOIN (
    SELECT emp_id, COUNT(ord_id) AS most_ord
    FROM orders
    GROUP BY emp_id
) t ON e.emp_id = t.emp_id
ORDER BY t.most_ord DESC;

#What is the total sales value processed by each employee?

SELECT e.emp_id, e.emp_name, t.tot_sale
FROM employees e
JOIN (
    SELECT o.emp_id, SUM(od.total_price) AS tot_sale
    FROM orders o
    JOIN order_details od ON o.ord_id = od.ord_id
    GROUP BY o.emp_id
) AS t ON e.emp_id = t.emp_id
ORDER BY t.tot_sale DESC;

#What is the average order value handled per employee?

SELECT 
    e.emp_id,
    e.emp_name,
    SUM(od.total_price) / COUNT(DISTINCT o.ord_id) AS avg_ord
FROM
    employees e
        JOIN
    orders o ON e.emp_id = o.emp_id
        JOIN
    order_details od ON o.ord_id = od.ord_id
GROUP BY e.emp_id
ORDER BY avg_ord DESC;

-- 6 . Order Details Deep Dive--------------------------------------------

#What is the relationship between quantity ordered and total price?

SELECT quantity,
       COUNT(*) AS num_lines,
       ROUND(AVG(each_price), 2) AS avg_unit_price,
       ROUND(AVG(total_price), 2) AS avg_total_price,
       ROUND(AVG(total_price / quantity), 2) AS price_per_unit
FROM order_details
GROUP BY quantity
ORDER BY quantity;

